def _generate_temporary_password(length: int = 14) -> str:
    """Genera una contraseña temporal robusta.

    Reglas: mínimo 1 mayúscula, 1 minúscula, 1 dígito y 1 símbolo.
    """
    if length < 8:
        length = 8
    categories = [
        secrets.choice(string.ascii_uppercase),
        secrets.choice(string.ascii_lowercase),
        secrets.choice(string.digits),
        secrets.choice("!@#$%^&*()-_=+[]{};:,.?/"),
    ]
    pool = string.ascii_letters + string.digits + "!@#$%^&*()-_=+[]{};:,.?/"
    remaining = [secrets.choice(pool) for _ in range(length - len(categories))]
    chars = categories + remaining
    secrets.SystemRandom().shuffle(chars)
    return "".join(chars)


@router.get("/", response_model=list[UserResponse])
def list_users(
    skip: int = 0,
    limit: int = 100,
    db: Session = Depends(get_db),
    _admin = Depends(require_admin),
):
    """Lista todos los usuarios del sistema (solo administradores)."""
    user_repo = UserRepository(db)
    users = user_repo.get_all(skip=skip, limit=limit)
    return users


@router.post("/", response_model=UserResponse, status_code=status.HTTP_201_CREATED)
def create_user_admin(
    data: UserCreate,
    request: Request,
    db: Session = Depends(get_db),
    _admin = Depends(require_admin),
):
    """Crea un usuario (solo administradores)."""
    user_repo = UserRepository(db)

    # Unicidad de email/username
    if user_repo.get_by_email(data.email):
        raise HTTPException(status_code=400, detail="Email ya registrado")
    if user_repo.get_by_username(data.username):
        raise HTTPException(status_code=400, detail="Username ya en uso")

    # Hash de password
    hashed = get_password_hash(data.password)

    from src.models.user import User
    user = User(
        email=data.email,
        username=data.username,
        full_name=data.full_name,
        hashed_password=hashed,
        is_active=True,
        is_superuser=False,
        role_id=data.role_id,
    )
    created = user_repo.create(user)

    # 🔒 AUDIT LOG: Registrar creación de usuario
    try:
        log_create(
            db=db,
            user_id=_admin.id,
            entity_name="users",
            entity_id=created.id,
            new_values={"email": created.email, "username": created.username, "role_id": created.role_id}
        )
    except Exception as audit_error:
        logger.error(f"❌ [AUDIT] Error al registrar creación de usuario {created.id}: {audit_error}")

    return created


@router.post("/{user_id}/reset-password", response_model=PasswordResetResponse)
def reset_password_admin(
    user_id: int,
    payload: Optional[PasswordResetRequest] = None,
    request: Request = None,
    db: Session = Depends(get_db),
    current_admin = Depends(require_admin),
):
    """
    Resetea contraseña de un usuario (solo administradores).
    
    Si se proporciona new_password en el payload, se usa esa.
    Si no, se autogenera una contraseña temporal robusta.
    """
    user_repo = UserRepository(db)
    user = user_repo.get(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="Usuario no encontrado")

    if user.id == current_admin.id:
        raise HTTPException(status_code=400, detail="No puedes resetear tu propia contraseña aquí")

    # Usar contraseña proporcionada o generar una
    if payload and payload.new_password:
        temp_password = payload.new_password
    else:
        temp_password = _generate_temporary_password()
    
    user.hashed_password = get_password_hash(temp_password)
    user_repo.update(user)

    # Audit
    try:
        AuditService.log_action(
            db=db,
            user_id=current_admin.id,
            action="user.reset_password",
            entity_type="User",
            entity_id=user.id,
            ip_address=get_client_ip(request),
            status="success",
            details={"method": "custom" if payload and payload.new_password else "autogenerated"},
        )
    except Exception:
        pass

    return PasswordResetResponse(user_id=user.id, temporary_password=temp_password)


@router.patch("/{user_id}/role", response_model=UserResponse)
def change_user_role(
    user_id: int,
    payload: RoleChangeRequest,
    request: Request,
    db: Session = Depends(get_db),
    current_admin = Depends(require_admin),
):
    """Cambia el rol de un usuario (solo administradores)."""
    user_repo = UserRepository(db)
    role_repo = RoleRepository(db)

    user = user_repo.get(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="Usuario no encontrado")

    if user.id == current_admin.id:
        raise HTTPException(status_code=400, detail="No puedes cambiar tu propio rol")

    role = role_repo.get(payload.role_id)
    if not role:
        raise HTTPException(status_code=404, detail="Rol no encontrado")

    # Capturar valor anterior para auditoría
    old_values = {"role_id": user.role_id}
    
    user.role_id = role.id
    updated = user_repo.update(user)

    # 🔒 AUDIT LOG: Registrar cambio de rol
    try:
        log_update(
            db=db,
            user_id=current_admin.id,
            entity_name="users",
            entity_id=user.id,
            old_values=old_values,
            new_values={"role_id": role.id, "role_name": role.name}
        )
    except Exception as audit_error:
        logger.error(f"❌ [AUDIT] Error al registrar cambio de rol de usuario {user.id}: {audit_error}")

    return updated


