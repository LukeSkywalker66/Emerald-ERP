@router.patch("/{user_id}", response_model=UserResponse)
def update_user(
    user_id: int,
    data: UserUpdate,
    request: Request,
    db: Session = Depends(get_db),
    current_admin = Depends(require_admin),
):
    """
    Actualiza los datos de un usuario (solo administradores).

    Permite modificar: email, username, full_name, role_id, is_active, is_superuser.
    No permite cambiar la contraseña (usar reset-password para eso).
    """
    user_repo = UserRepository(db)
    user = user_repo.get(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="Usuario no encontrado")

    # No permitir que un admin se modifique a sí mismo el rol o superuser
    if user.id == current_admin.id:
        if data.role_id is not None or data.is_superuser is not None:
            raise HTTPException(
                status_code=400,
                detail="No puedes modificar tu propio rol o permisos de superusuario"
            )

    # Verificar unicidad de email si cambió
    if data.email is not None and data.email != user.email:
        if user_repo.get_by_email(data.email):
            raise HTTPException(status_code=400, detail="Email ya registrado")
        user.email = data.email

    # Verificar unicidad de username si cambió
    if data.username is not None and data.username != user.username:
        if user_repo.get_by_username(data.username):
            raise HTTPException(status_code=400, detail="Username ya en uso")
        user.username = data.username

    # Capturar valores anteriores para auditoría
    old_values = get_entity_dict(user)

    if data.full_name is not None:
        user.full_name = data.full_name
    if data.is_active is not None:
        user.is_active = data.is_active
    if data.is_superuser is not None:
        user.is_superuser = data.is_superuser
    if data.role_id is not None:
        role_repo = RoleRepository(db)
        role = role_repo.get(data.role_id)
        if not role:
            raise HTTPException(status_code=404, detail="Rol no encontrado")
        user.role_id = role.id

    updated = user_repo.update(user)

    # 🔒 AUDIT LOG: Registrar actualización de usuario
    try:
        log_update(
            db=db,
            user_id=current_admin.id,
            entity_name="users",
            entity_id=user.id,
            old_values=old_values,
            new_values=get_entity_dict(updated)
        )
    except Exception as audit_error:
        logger.error(f"❌ [AUDIT] Error al registrar actualización de usuario {user.id}: {audit_error}")

    return updated


@router.delete("/{user_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_user_permanently(
    user_id: int,
    request: Request,
    db: Session = Depends(get_db),
    current_admin = Depends(require_admin),
):
    """
    Elimina permanentemente un usuario (solo administradores).
    
    SOLO permite eliminar usuarios SIN datos históricos:
    - Sin membresías en equipos (team_memberships)
    - Sin acciones de auditoría
    - Sin último login (nunca usó el sistema)
    
    Para usuarios con historial, usar PATCH /status (desactivar).
    """
    user_repo = UserRepository(db)
    user = user_repo.get(user_id)
    if not user:
        raise HTTPException(status_code=404, detail="Usuario no encontrado")

    if user.id == current_admin.id:
        raise HTTPException(
            status_code=400, 
            detail="No puedes eliminar tu propia cuenta"
        )

    # Verificar que el usuario no tenga datos históricos
    validation_errors = []

    # 1. Team memberships
    if user.team_memberships and len(user.team_memberships) > 0:
        validation_errors.append(
            f"tiene {len(user.team_memberships)} asignación(es) en equipos"
        )

    # 2. Último login (si usó el sistema)
    if user.last_login is not None:
        validation_errors.append("ya inició sesión en el sistema")

    # 3. Auditoría (si ejecutó acciones)
    try:
        from src.models.audit import AuditLog
        audit_count = db.query(AuditLog).filter(AuditLog.user_id == user_id).count()
        if audit_count > 0:
            validation_errors.append(f"tiene {audit_count} acción(es) registrada(s)")
    except Exception:
        # Si no existe tabla de auditoría, continuar
        pass

    # Si tiene datos, rechazar eliminación
    if validation_errors:
        raise HTTPException(
            status_code=400,
            detail={
                "message": "No se puede eliminar: usuario con datos históricos",
                "reasons": validation_errors,
                "suggestion": "Usar PATCH /status para desactivar en lugar de eliminar"
            }
        )

    # Si no tiene datos, proceder con eliminación
    old_values = {"username": user.username, "email": user.email, "role_id": user.role_id}
    user_id_for_audit = user.id
    username = user.username
    email = user.email
    
    user_repo.delete(user_id)

    # 🔒 AUDIT LOG: Registrar eliminación de usuario
    try:
        log_delete(
            db=db,
            user_id=current_admin.id,
            entity_name="users",
            entity_id=user_id_for_audit,
            old_values=old_values
        )
    except Exception as audit_error:
        logger.error(f"❌ [AUDIT] Error al registrar eliminación de usuario {user_id_for_audit}: {audit_error}")

    return None
